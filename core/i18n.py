DICTS = {'ru': RU}


def tr(text, **params):
    """Tarjima qiladi va {nom} o'rinlarini to'ldiradi: tr("{name}: yetarli emas", name=p.name)"""
    result = translate(text)
    return result.format(**params) if params else result


def translate(text, lang=None):
    lang = lang or current_lang.get()
    if lang == 'uz' or text is None:
        return text
    return DICTS.get(lang, {}).get(str(text), text)
